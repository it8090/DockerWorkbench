export const messages = { en, "zh-CN": zh };
export type Translator = (
  key: TranslationKey,
  values?: Record<string, string | number>,
) => string;
export function translator(language: Language): Translator {
  return (key, values) => {
    let text: string = messages[language][key] || en[key];
    for (const [k, v] of Object.entries(values || {}))
      text = text.replaceAll(`{${k}}`, String(v));
    return text;
  };
}
export const I18nContext = createContext<{ language: Language; t: Translator }>(
  { language: "zh-CN", t: translator("zh-CN") },
);
export const useI18n = () => useContext(I18nContext);
